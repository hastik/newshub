#!/usr/bin/env python3
"""
Static site generator for newshub with directory listings.
Generates index.html for each directory and renders markdown files.
"""

import os
import sys
import yaml
import markdown
from pathlib import Path
from datetime import datetime
from html import escape
from urllib.parse import quote

# Directories to exclude from listing
EXCLUDE_DIRS = {'.git', '.github', 'scripts', '_site', '__pycache__'}
EXCLUDE_FILES = {'.gitignore', '.DS_Store'}

def load_yaml_front_matter(file_path):
    """Load YAML front matter from a markdown file."""
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            content = f.read()
        
        if not content.startswith('---'):
            return None, content
        
        parts = content.split('---', 2)
        if len(parts) < 3:
            return None, content
        
        try:
            front_matter = yaml.safe_load(parts[1])
            body = parts[2].strip()
            return front_matter, body
        except yaml.YAMLError:
            return None, content
    except Exception as e:
        print(f"Warning: Could not read {file_path}: {e}")
        return None, ""

def get_html_head(title, parent_path=""):
    """Generate HTML head with title and styling."""
    # Calculate path to root for CSS
    depth = parent_path.count('/') if parent_path else 0
    root_path = '../' * depth if depth > 0 else './'
    
    return f"""<!DOCTYPE html>
<html lang="cs">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{escape(title)} - newshub</title>
    <link rel="stylesheet" href="{root_path}style.css">
</head>
<body>
"""

def get_html_footer():
    """Generate HTML footer."""
    return """
<footer>
    <p>Generated by newshub static site generator</p>
</footer>
</body>
</html>
"""

def render_markdown_page(md_path, output_path, front_matter, body, source_dir='.'):
    """Render a markdown file to HTML."""
    # Convert markdown to HTML
    md = markdown.Markdown(extensions=['extra', 'codehilite', 'toc'])
    html_content = md.convert(body)
    
    # Calculate relative path to root and to raw file
    rel_path = os.path.relpath(md_path, start=os.path.dirname(os.path.dirname(output_path)))
    
    # Build title from front matter if available
    if front_matter and 'title' in front_matter:
        title = front_matter['title']
    else:
        title = os.path.basename(md_path)
    
    # Calculate path components for navigation
    abs_md_path = os.path.abspath(md_path)
    abs_source_dir = os.path.abspath(source_dir)
    rel_md_path = os.path.relpath(abs_md_path, abs_source_dir)
    parts = Path(rel_md_path).parts
    parent_path = '/'.join(parts[:-1]) if len(parts) > 1 else ''
    
    html = get_html_head(title, parent_path)
    
    # Breadcrumb navigation
    html += '<nav class="breadcrumb">\n'
    html += '<a href="' + ('../' * len(parts) if len(parts) > 1 else './') + 'index.html">newshub</a>'
    
    for i, part in enumerate(parts[:-1]):
        html += ' / '
        rel_link = '../' * (len(parts) - i - 2) + 'index.html' if i < len(parts) - 2 else 'index.html'
        html += f'<a href="{rel_link}">{escape(part)}</a>'
    
    html += ' / ' + escape(parts[-1])
    html += '\n</nav>\n'
    
    # Article header with metadata
    if front_matter:
        html += '<article>\n'
        html += f'<header class="article-header">\n'
        html += f'<h1>{escape(title)}</h1>\n'
        
        # Metadata
        html += '<div class="article-meta">\n'
        
        if 'source' in front_matter:
            html += f'<span class="source">Zdroj: {escape(front_matter["source"])}</span>'
        
        if 'published' in front_matter:
            html += f'<span class="date">Publikováno: {escape(str(front_matter["published"]))}</span>'
        
        if 'added' in front_matter:
            html += f'<span class="date">Přidáno: {escape(str(front_matter["added"]))}</span>'
        
        if 'category' in front_matter:
            html += f'<span class="category">Kategorie: {escape(front_matter["category"])}</span>'
        
        if 'tags' in front_matter and isinstance(front_matter['tags'], list):
            html += '<div class="tags">'
            for tag in front_matter['tags']:
                html += f'<span class="tag">{escape(tag)}</span>'
            html += '</div>'
        
        if 'url' in front_matter:
            html += f'<div class="original-url"><a href="{escape(front_matter["url"])}" target="_blank" rel="noopener">Původní článek ↗</a></div>'
        
        html += '</div>\n'  # article-meta
        html += '</header>\n'
        
        # Content
        html += '<div class="article-content">\n'
        html += html_content
        html += '</div>\n'
        
        # Link to raw markdown
        html += f'<footer class="article-footer">\n'
        html += f'<a href="{escape(rel_path)}" class="raw-link">Zobrazit zdrojový markdown</a>\n'
        html += '</footer>\n'
        
        html += '</article>\n'
    else:
        # No front matter, just render the content
        html += '<article>\n'
        html += f'<h1>{escape(title)}</h1>\n'
        html += '<div class="article-content">\n'
        html += html_content
        html += '</div>\n'
        html += f'<footer class="article-footer">\n'
        html += f'<a href="{escape(rel_path)}" class="raw-link">Zobrazit zdrojový markdown</a>\n'
        html += '</footer>\n'
        html += '</article>\n'
    
    html += get_html_footer()
    
    # Write output
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(html)

def generate_directory_index(dir_path, output_dir, rel_path=""):
    """Generate index.html for a directory with listings."""
    entries = []
    
    # Scan directory
    for entry in sorted(os.listdir(dir_path)):
        if entry in EXCLUDE_FILES or entry in EXCLUDE_DIRS:
            continue
        
        entry_path = os.path.join(dir_path, entry)
        
        if os.path.isdir(entry_path):
            entries.append({
                'name': entry,
                'type': 'dir',
                'path': entry + '/',
                'title': None
            })
        elif entry.endswith('.md'):
            # Load front matter to get title
            front_matter, _ = load_yaml_front_matter(entry_path)
            title = front_matter.get('title') if front_matter else None
            
            entries.append({
                'name': entry,
                'type': 'file',
                'path': entry.replace('.md', '.html'),
                'raw_path': entry,
                'title': title
            })
        else:
            # Other files (YAML, etc.)
            entries.append({
                'name': entry,
                'type': 'file',
                'path': entry,
                'raw_path': entry,
                'title': None
            })
    
    # Build HTML
    dir_name = os.path.basename(dir_path) if dir_path != '.' else 'newshub'
    html = get_html_head(dir_name, rel_path)
    
    # Breadcrumb navigation
    html += '<nav class="breadcrumb">\n'
    parts = rel_path.split('/') if rel_path else []
    
    if not parts or parts == ['']:
        html += '<strong>newshub</strong>'
    else:
        html += '<a href="' + ('../' * len(parts)) + 'index.html">newshub</a>'
        for i, part in enumerate(parts):
            if part:
                html += ' / '
                if i < len(parts) - 1:
                    rel_link = '../' * (len(parts) - i - 1) + 'index.html'
                    html += f'<a href="{rel_link}">{escape(part)}</a>'
                else:
                    html += f'<strong>{escape(part)}</strong>'
    
    html += '\n</nav>\n'
    
    # Directory listing
    html += f'<h1>Obsah adresáře {escape(dir_name)}</h1>\n'
    
    # Parent directory link if not at root
    if rel_path:
        html += '<div class="directory-listing">\n'
        html += '<div class="entry parent-dir">\n'
        html += '<span class="icon">📁</span>\n'
        html += '<a href="../index.html">.. (nadřazený adresář)</a>\n'
        html += '</div>\n'
    else:
        html += '<div class="directory-listing">\n'
    
    # List directories first, then files
    dirs = [e for e in entries if e['type'] == 'dir']
    files = [e for e in entries if e['type'] == 'file']
    
    for entry in dirs:
        html += '<div class="entry directory">\n'
        html += '<span class="icon">📁</span>\n'
        html += f'<a href="{escape(entry["path"])}index.html">{escape(entry["name"])}/</a>\n'
        html += '</div>\n'
    
    for entry in files:
        html += '<div class="entry file">\n'
        
        if entry['name'].endswith('.md'):
            html += '<span class="icon">📄</span>\n'
            html += f'<a href="{escape(entry["path"])}">{escape(entry["name"])}</a>\n'
            
            if entry.get('title'):
                html += f'<span class="file-title"> — {escape(entry["title"])}</span>\n'
            
            html += f'<span class="raw-link-inline"> [<a href="{escape(entry["raw_path"])}">raw</a>]</span>\n'
        else:
            html += '<span class="icon">📄</span>\n'
            html += f'<a href="{escape(entry["path"])}">{escape(entry["name"])}</a>\n'
        
        html += '</div>\n'
    
    html += '</div>\n'
    html += get_html_footer()
    
    # Write index.html
    index_path = os.path.join(output_dir, 'index.html')
    os.makedirs(output_dir, exist_ok=True)
    with open(index_path, 'w', encoding='utf-8') as f:
        f.write(html)

def copy_file(src, dst):
    """Copy a file to destination."""
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(src, 'rb') as fsrc:
        with open(dst, 'wb') as fdst:
            fdst.write(fsrc.read())

def generate_site(source_dir, output_dir):
    """Generate the complete static site."""
    print(f"Generating site from {source_dir} to {output_dir}")
    
    # Create output directory
    os.makedirs(output_dir, exist_ok=True)
    
    # Walk through source directory
    for root, dirs, files in os.walk(source_dir):
        # Skip excluded directories
        dirs[:] = [d for d in dirs if d not in EXCLUDE_DIRS]
        
        # Calculate relative path
        rel_root = os.path.relpath(root, source_dir)
        if rel_root == '.':
            rel_root = ''
        
        output_subdir = os.path.join(output_dir, rel_root) if rel_root else output_dir
        
        # Generate directory index
        generate_directory_index(root, output_subdir, rel_root)
        print(f"  Generated index for: {rel_root if rel_root else '(root)'}")
        
        # Process files
        for file in files:
            if file in EXCLUDE_FILES:
                continue
            
            src_path = os.path.join(root, file)
            
            if file.endswith('.md'):
                # Render markdown to HTML
                front_matter, body = load_yaml_front_matter(src_path)
                html_file = file.replace('.md', '.html')
                dst_path = os.path.join(output_subdir, html_file)
                render_markdown_page(src_path, dst_path, front_matter, body, source_dir)
                print(f"  Rendered: {os.path.join(rel_root, file)}")
                
                # Also copy raw markdown
                raw_dst = os.path.join(output_subdir, file)
                copy_file(src_path, raw_dst)
            else:
                # Copy other files as-is
                dst_path = os.path.join(output_subdir, file)
                copy_file(src_path, dst_path)
                print(f"  Copied: {os.path.join(rel_root, file)}")
    
    # Generate CSS
    generate_css(output_dir)
    print("  Generated style.css")
    
    print(f"\n✅ Site generated successfully in {output_dir}")

